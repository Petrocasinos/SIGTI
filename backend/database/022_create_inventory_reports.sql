BEGIN;

CREATE TABLE IF NOT EXISTS test.inventory_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES test.usuarios(id) ON DELETE CASCADE,
  equipment_code VARCHAR(6) NOT NULL CHECK (equipment_code ~ '^EF[0-9]{4}$'),
  peripherals JSONB NOT NULL DEFAULT '{}'::jsonb,
  status VARCHAR(30) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'validated', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_test_inventory_reports_status
  ON test.inventory_reports(status);

DROP TRIGGER IF EXISTS trg_inventory_reports_updated_at ON test.inventory_reports;
CREATE TRIGGER trg_inventory_reports_updated_at
BEFORE UPDATE ON test.inventory_reports
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE test.inventory_reports ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON test.inventory_reports TO service_role;
GRANT USAGE, SELECT ON SEQUENCE test.inventory_reports_id_seq TO service_role;

COMMIT;
