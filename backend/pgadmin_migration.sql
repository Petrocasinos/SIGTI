CREATE TABLE IF NOT EXISTS public.peripheral_stock (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_type VARCHAR(30) NOT NULL CHECK (item_type IN ('mouse', 'keyboard', 'charge', 'cooling_base', 'mouse_pad')),
  brand VARCHAR(100), reference VARCHAR(150), model VARCHAR(150),
  location VARCHAR(150) NOT NULL DEFAULT 'Área de Sistemas',
  quantity_total INTEGER NOT NULL DEFAULT 0 CHECK (quantity_total >= 0),
  quantity_available INTEGER NOT NULL DEFAULT 0 CHECK (quantity_available >= 0),
  quantity_assigned INTEGER NOT NULL DEFAULT 0 CHECK (quantity_assigned >= 0),
  quantity_cleaning INTEGER NOT NULL DEFAULT 0 CHECK (quantity_cleaning >= 0),
  quantity_damaged INTEGER NOT NULL DEFAULT 0 CHECK (quantity_damaged >= 0),
  quantity_retired INTEGER NOT NULL DEFAULT 0 CHECK (quantity_retired >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT peripheral_stock_quantity_balance CHECK
    (quantity_total = quantity_available + quantity_assigned + quantity_cleaning + quantity_damaged + quantity_retired)
);

CREATE TABLE IF NOT EXISTS public.assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  equipment_id BIGINT NOT NULL REFERENCES public.maintenances(id) ON DELETE RESTRICT,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'returned', 'cancelled')),
  delivered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), returned_at TIMESTAMPTZ,
  assigned_by BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  received_by BIGINT REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  delivery_notes TEXT, return_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT assignment_return_date CHECK
    ((status IN ('draft', 'active') AND returned_at IS NULL) OR
     (status IN ('returned', 'cancelled') AND returned_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.assignment_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES public.assignments(id) ON DELETE RESTRICT,
  peripheral_stock_id BIGINT NOT NULL REFERENCES public.peripheral_stock(id) ON DELETE RESTRICT,
  quantity_delivered INTEGER NOT NULL DEFAULT 1 CHECK (quantity_delivered > 0),
  quantity_returned INTEGER NOT NULL DEFAULT 0 CHECK (quantity_returned >= 0 AND quantity_returned <= quantity_delivered),
  return_condition VARCHAR(20) CHECK (return_condition IN ('good', 'cleaning', 'damaged', 'missing')),
  notes TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT assignment_item_unique_per_stock UNIQUE (assignment_id, peripheral_stock_id),
  CONSTRAINT assignment_item_return_data CHECK
    ((quantity_returned = 0 AND return_condition IS NULL) OR (quantity_returned > 0 AND return_condition IS NOT NULL))
);

