CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
$$;

DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['tickets','peripheral_stock','assignments','assignment_items','area_peripheral_counts','equipment_peripheral_counts','inventory_reports'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON public.%I', table_name, table_name);
    EXECUTE format('CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', table_name, table_name);
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.validate_cooling_base_assignment()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE current_item_type TEXT; current_equipment_type TEXT;
BEGIN
  SELECT stock.item_type, equipment.equipment_type INTO current_item_type, current_equipment_type
  FROM public.assignments assignment
  JOIN public.peripheral_stock stock ON stock.id = NEW.peripheral_stock_id
  JOIN public.maintenances equipment ON equipment.id = assignment.equipment_id
  WHERE assignment.id = NEW.assignment_id;
  IF current_item_type = 'cooling_base' AND current_equipment_type NOT IN ('Portátil') THEN
    RAISE EXCEPTION 'Una base refrigerante solo se puede asignar con un portátil.';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS validate_cooling_base_assignment_trigger ON public.assignment_items;
CREATE TRIGGER validate_cooling_base_assignment_trigger
BEFORE INSERT OR UPDATE OF assignment_id, peripheral_stock_id ON public.assignment_items
FOR EACH ROW EXECUTE FUNCTION public.validate_cooling_base_assignment();

CREATE OR REPLACE FUNCTION public.create_assignment(
  p_employee_id BIGINT, p_equipment_id BIGINT, p_assigned_by BIGINT,
  p_stock_ids BIGINT[], p_notes TEXT DEFAULT NULL
) RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE new_assignment_id BIGINT; selected_equipment_type TEXT;
  has_mouse BOOLEAN; has_keyboard BOOLEAN; has_cooling_base BOOLEAN; stock_count INTEGER;
BEGIN
  IF COALESCE(cardinality(p_stock_ids), 0) < 2 THEN RAISE EXCEPTION 'El kit debe incluir un mouse y un teclado.'; END IF;
  IF (SELECT COUNT(DISTINCT stock_id) FROM unnest(p_stock_ids) AS stock_id) <> cardinality(p_stock_ids) THEN RAISE EXCEPTION 'No se puede seleccionar el mismo periférico más de una vez.'; END IF;
  SELECT equipment_type INTO selected_equipment_type FROM public.maintenances WHERE id = p_equipment_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El equipo seleccionado no existe.'; END IF;
  PERFORM 1 FROM public.usuarios WHERE id = p_employee_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'El empleado seleccionado no existe.'; END IF;
  IF EXISTS (SELECT 1 FROM public.assignments WHERE status = 'active' AND (employee_id = p_employee_id OR equipment_id = p_equipment_id)) THEN RAISE EXCEPTION 'El empleado o el equipo ya tiene un préstamo activo.'; END IF;
  PERFORM 1 FROM public.peripheral_stock WHERE id = ANY(p_stock_ids) FOR UPDATE;
  SELECT COUNT(*), BOOL_OR(item_type = 'mouse'), BOOL_OR(item_type = 'keyboard'), BOOL_OR(item_type = 'cooling_base')
    INTO stock_count, has_mouse, has_keyboard, has_cooling_base
    FROM public.peripheral_stock WHERE id = ANY(p_stock_ids) AND status = 'active' AND quantity_available >= 1;
  IF stock_count <> cardinality(p_stock_ids) THEN RAISE EXCEPTION 'Uno o más periféricos ya no están disponibles.'; END IF;
  IF NOT COALESCE(has_mouse, FALSE) OR NOT COALESCE(has_keyboard, FALSE) THEN RAISE EXCEPTION 'El kit requiere un mouse y un teclado.'; END IF;
  IF COALESCE(has_cooling_base, FALSE) AND selected_equipment_type <> 'Portátil' THEN RAISE EXCEPTION 'La base refrigerante solo puede asignarse a un portátil.'; END IF;
  INSERT INTO public.assignments (employee_id, equipment_id, status, assigned_by, delivery_notes)
    VALUES (p_employee_id, p_equipment_id, 'draft', p_assigned_by, NULLIF(TRIM(p_notes), '')) RETURNING id INTO new_assignment_id;
  INSERT INTO public.assignment_items (assignment_id, peripheral_stock_id, quantity_delivered)
    SELECT new_assignment_id, stock_id, 1 FROM unnest(p_stock_ids) AS stock_id;
  UPDATE public.peripheral_stock SET quantity_available = quantity_available - 1, quantity_assigned = quantity_assigned + 1, updated_at = NOW() WHERE id = ANY(p_stock_ids);
  INSERT INTO public.peripheral_stock_movements (peripheral_stock_id, assignment_id, movement_type, quantity, recorded_by)
    SELECT stock_id, new_assignment_id, 'assignment', 1, p_assigned_by FROM unnest(p_stock_ids) AS stock_id;
  UPDATE public.assignments SET status = 'active', updated_at = NOW() WHERE id = new_assignment_id;
  RETURN jsonb_build_object('id', new_assignment_id, 'status', 'active');
END;
$$;

CREATE OR REPLACE FUNCTION public.return_assignment(
  p_assignment_id BIGINT, p_received_by BIGINT, p_items JSONB, p_notes TEXT DEFAULT NULL
) RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE current_item RECORD; input_item JSONB; item_condition TEXT; returned_quantity INTEGER;
BEGIN
  PERFORM 1 FROM public.assignments WHERE id = p_assignment_id AND status = 'active' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'El préstamo no existe o ya fue devuelto.'; END IF;
  FOR current_item IN SELECT id, peripheral_stock_id, quantity_delivered FROM public.assignment_items WHERE assignment_id = p_assignment_id FOR UPDATE LOOP
    SELECT value INTO input_item FROM jsonb_array_elements(p_items) WHERE (value ->> 'assignment_item_id')::BIGINT = current_item.id;
    IF input_item IS NULL THEN RAISE EXCEPTION 'Falta el estado de uno de los periféricos asignados.'; END IF;
    item_condition := input_item ->> 'condition';
    IF item_condition NOT IN ('good', 'cleaning', 'damaged', 'missing') THEN RAISE EXCEPTION 'El estado de devolución no es válido.'; END IF;
    returned_quantity := current_item.quantity_delivered;
    UPDATE public.assignment_items SET quantity_returned = returned_quantity, return_condition = item_condition, updated_at = NOW() WHERE id = current_item.id;
    UPDATE public.peripheral_stock SET quantity_assigned = quantity_assigned - returned_quantity, quantity_available = quantity_available + CASE WHEN item_condition = 'good' THEN returned_quantity ELSE 0 END, quantity_cleaning = quantity_cleaning + CASE WHEN item_condition = 'cleaning' THEN returned_quantity ELSE 0 END, quantity_damaged = quantity_damaged + CASE WHEN item_condition = 'damaged' THEN returned_quantity ELSE 0 END, quantity_retired = quantity_retired + CASE WHEN item_condition = 'missing' THEN returned_quantity ELSE 0 END, updated_at = NOW() WHERE id = current_item.peripheral_stock_id AND quantity_assigned >= returned_quantity;
    IF NOT FOUND THEN RAISE EXCEPTION 'El stock asignado del periférico no es suficiente para registrar la devolución.'; END IF;
    INSERT INTO public.peripheral_stock_movements (peripheral_stock_id, assignment_id, movement_type, quantity, notes, recorded_by) VALUES (current_item.peripheral_stock_id, p_assignment_id, CASE item_condition WHEN 'good' THEN 'return_good' WHEN 'cleaning' THEN 'send_to_cleaning' WHEN 'damaged' THEN 'damaged' ELSE 'retired' END, returned_quantity, CASE WHEN item_condition = 'missing' THEN 'Periférico no devuelto (faltante).' ELSE NULL END, p_received_by);
  END LOOP;
  UPDATE public.assignments SET status = 'returned', returned_at = NOW(), received_by = p_received_by, return_notes = NULLIF(TRIM(p_notes), ''), updated_at = NOW() WHERE id = p_assignment_id;
  RETURN jsonb_build_object('id', p_assignment_id, 'status', 'returned');
END;
$$;

