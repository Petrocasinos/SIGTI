  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  lastname TEXT,
  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role_id BIGINT NOT NULL REFERENCES public.roles(id) ON DELETE RESTRICT,
  area TEXT NOT NULL DEFAULT 'ÁREA NO DEFINIDA',
  reset_token_hash TEXT,
  reset_token_expires_at TIMESTAMP WITHOUT TIME ZONE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
  IF to_regclass('public.users') IS NOT NULL THEN
    INSERT INTO public.usuarios
      (id, name, lastname, username, email, password, role_id, created_at)
    SELECT u.id::BIGINT, u.name, u.lastname, u.username, u.email, u.password,
           u.role_id::BIGINT, u.created_at::TIMESTAMPTZ
    FROM public.users u
    WHERE NOT EXISTS (
      SELECT 1 FROM public.usuarios target WHERE target.id = u.id::BIGINT
    )
    ON CONFLICT (username) DO NOTHING;
  END IF;

  IF to_regclass('test.roles') IS NOT NULL THEN
    INSERT INTO public.roles (id, name)
    SELECT id::BIGINT, name FROM test.roles
    ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name;
  END IF;

  IF to_regclass('test.usuarios') IS NOT NULL THEN
    INSERT INTO public.usuarios
      (id, name, lastname, username, email, password, role_id, area, created_at)
    SELECT id::BIGINT, name, lastname, username, email, password,
           role_id::BIGINT, COALESCE(area, 'ÁREA NO DEFINIDA'), created_at::TIMESTAMPTZ
    FROM test.usuarios
    ON CONFLICT (id) DO UPDATE SET
      name = EXCLUDED.name,
      lastname = EXCLUDED.lastname,
      username = EXCLUDED.username,
      email = EXCLUDED.email,
      password = EXCLUDED.password,
      role_id = EXCLUDED.role_id,
      area = EXCLUDED.area,
      created_at = EXCLUDED.created_at;
  END IF;
END $$;

