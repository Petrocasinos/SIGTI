-- SIGTI - Esquema definitivo de producción
--
-- Consolida las migraciones 001..022 en el esquema public.
--
-- Propiedades:
--   * Puede ejecutarse sobre una base nueva o sobre la base que ya contiene
--     los objetos de SIGTI en test.
--   * Cuando existe test, copia sus datos a public antes de dejar listas las
--     funciones RPC y los permisos del backend.
--   * No elimina el esquema test ni sus datos: se conserva como respaldo para
--     validación y retiro posterior mediante una migración separada.
--
-- Ejecutar con un rol propietario de las tablas (por ejemplo, postgres).

